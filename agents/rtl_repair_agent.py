import json
import os
import re
from pathlib import Path

from chia.base.ChiaFunction import get
from chia.models.opencode import (
    OpenCodeLLM,
    AdditionalModelProvider,
    QueryResult,
)


PROJECT_ROOT = Path(__file__).resolve().parents[1]

PERSIST_ROOT = Path(
    os.environ.get("ACCELCLOSURE_ROOT", str(PROJECT_ROOT))
).expanduser().resolve()

RTL_DIR = PERSIST_ROOT / "rtl"
RESULTS_DIR = PERSIST_ROOT / "results"

MODEL = "google-vertex/gemini-3.1-pro-preview"


def load_json(path):
    with Path(path).open() as f:
        return json.load(f)


def extract_json(text):
    text = text.strip()

    text = re.sub(
        r"^```(?:json)?\s*",
        "",
        text,
        flags=re.IGNORECASE,
    )
    text = re.sub(r"\s*```$", "", text)

    first = text.find("{")
    last = text.rfind("}")

    if first == -1 or last == -1 or last <= first:
        raise ValueError("No JSON object found in repair response")

    return json.loads(text[first:last + 1])


def make_prompt(
    pe_rtl,
    array_rtl,
    lint_report,
    golden_context,
):
    return f"""
You are the AccelClosure RTL Repair Agent.

A real Verilator run has produced engineering feedback on RTL previously
generated by another agent.

Your task is to make the SMALLEST CORRECT RTL CHANGE required to resolve
the tool feedback while preserving the validated accelerator architecture.

Do not redesign the accelerator unnecessarily.

================ REAL TOOL FEEDBACK ================

{json.dumps(lint_report, indent=2)}

================ CURRENT PE RTL ================

{pe_rtl}

================ CURRENT ARRAY RTL ================

{array_rtl}

================ GOLDEN REFERENCE CONTEXT ================

{json.dumps(golden_context, indent=2)}

================ REPAIR RULES ================

1. Treat Verilator output as authoritative tool evidence.
2. Preserve the 16x16 parameterizable weight-stationary architecture.
3. Preserve signed INT8 multiplication and INT32 accumulation.
4. The multiplication result must be EXPLICITLY and correctly sign-extended
   to ACC_W before accumulation.
5. Do not suppress the warning with lint pragmas.
6. Do not use unsigned casts to hide the problem.
7. Do not change interfaces unless absolutely necessary.
8. Do not add clock gating, power gating, DMA, CPU interfaces, or unrelated logic.
9. Do not claim the repair works until Verilator is rerun.
10. Return synthesizable SystemVerilog only inside the JSON file contents.
11. No Markdown fences.

Return exactly:

{{
  "repair_version": "1.0",
  "failure_class": "...",
  "root_cause": "...",
  "repair_summary": "...",
  "golden_principles_used": [],
  "files": [
    {{
      "path": "rtl/accelclosure_ws_pe.sv",
      "content": "..."
    }},
    {{
      "path": "rtl/accelclosure_ws_array.sv",
      "content": "..."
    }}
  ],
  "verification_required": [
    "Verilator lint must be rerun",
    "Functional verification must still be performed"
  ]
}}
"""


def validate_bundle(bundle):
    errors = []

    files = bundle.get("files", [])

    expected = {
        "rtl/accelclosure_ws_pe.sv",
        "rtl/accelclosure_ws_array.sv",
    }

    actual = {
        f.get("path")
        for f in files
        if isinstance(f, dict)
    }

    if actual != expected:
        errors.append(
            f"Expected {sorted(expected)}, got {sorted(actual)}"
        )

    for item in files:
        content = item.get("content", "")

        if not content.strip():
            errors.append(
                f"Empty content: {item.get('path')}"
            )

        if "```" in content:
            errors.append(
                f"Markdown fence in {item.get('path')}"
            )

    return errors


def main():
    project = os.environ.get("GOOGLE_CLOUD_PROJECT")

    if not project:
        raise RuntimeError("GOOGLE_CLOUD_PROJECT is not set")

    pe_path = RTL_DIR / "accelclosure_ws_pe.sv"
    array_path = RTL_DIR / "accelclosure_ws_array.sv"

    lint_path = RESULTS_DIR / "verilator_lint_report.json"
    context_path = RESULTS_DIR / "design_contract_golden_context.json"

    pe_rtl = pe_path.read_text()
    array_rtl = array_path.read_text()

    lint_report = load_json(lint_path)
    golden_context = load_json(context_path)

    if lint_report.get("status") != "PASS":
        print(
            "[AccelClosure] Note: lint report contains a failing result."
        )

    vertex = AdditionalModelProvider(
        id="google-vertex",
        npm="@ai-sdk/google-vertex",
        name="Google Vertex AI",
        models=["gemini-3.1-pro-preview"],
        options={
            "project": project,
            "location": "global",
        },
    )

    llm = OpenCodeLLM(
        model=MODEL,
        additional_providers=[vertex],
    )

    prompt = make_prompt(
        pe_rtl,
        array_rtl,
        lint_report,
        golden_context,
    )

    print("[AccelClosure] REAL_TOOL_FEEDBACK_LOADED")
    print("[AccelClosure] Dispatching repair to Gemini...")

    response: QueryResult = get(
        llm.prompt.chia_remote(
            llm,
            prompt,
        )
    )

    raw = response.result

    RESULTS_DIR.mkdir(
        parents=True,
        exist_ok=True,
    )

    (
        RESULTS_DIR
        / "rtl_repair_raw.txt"
    ).write_text(raw)

    bundle = extract_json(raw)

    errors = validate_bundle(bundle)

    if errors:
        raise RuntimeError(
            "Repair bundle invalid: "
            + "; ".join(errors)
        )

    # Preserve pre-repair RTL.
    backup_dir = RTL_DIR / "revisions" / "v1_before_verilator_repair"
    backup_dir.mkdir(
        parents=True,
        exist_ok=True,
    )

    (backup_dir / pe_path.name).write_text(pe_rtl)
    (backup_dir / array_path.name).write_text(array_rtl)

    # Write repaired RTL.
    for item in bundle["files"]:
        destination = PERSIST_ROOT / item["path"]
        destination.write_text(item["content"])

        print(
            "[AccelClosure] REPAIRED:",
            destination,
        )

    report = {
        "status": "REPAIRED_UNVERIFIED",
        "repair_version": bundle.get("repair_version"),
        "failure_class": bundle.get("failure_class"),
        "root_cause": bundle.get("root_cause"),
        "repair_summary": bundle.get("repair_summary"),
        "golden_principles_used": bundle.get(
            "golden_principles_used", []
        ),
        "verification_required": bundle.get(
            "verification_required", []
        ),
        "source_tool": "Verilator",
        "source_report": "results/verilator_lint_report.json",
        "pre_repair_backup":
            "rtl/revisions/v1_before_verilator_repair",
        "verified": False,
    }

    (
        RESULTS_DIR
        / "rtl_repair_report.json"
    ).write_text(
        json.dumps(report, indent=2)
    )

    print(
        json.dumps(
            report,
            indent=2,
        )
    )


if __name__ == "__main__":
    main()
